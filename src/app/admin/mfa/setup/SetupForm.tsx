"use client";

import { useActionState, useState, useTransition } from "react";
import { cancelEnrol, confirmEnrol, startEnrol, type EnrolStart, type MfaState } from "../actions";

export default function SetupForm({ next }: { next: string }) {
  const [started, setStarted] = useState<EnrolStart | null>(null);
  const [pending, start] = useTransition();
  const [state, action, confirming] = useActionState<MfaState, FormData>(confirmEnrol, {});

  if (!started?.factorId) {
    return (
      <div className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm text-charcoal">
          <li>Install an authenticator app on your phone (Google Authenticator, Microsoft Authenticator, Authy or 1Password).</li>
          <li>Press <strong>Set up</strong> and scan the QR code.</li>
          <li>Type the 6-digit code the app shows.</li>
        </ol>
        {started?.error && <p role="alert" className="rounded-md border border-red-200 bg-red-50 px-3 py-2 text-sm text-red-800">{started.error}</p>}
        <button type="button" disabled={pending} onClick={() => start(async () => setStarted(await startEnrol()))} className="btn-primary w-full justify-center disabled:opacity-60">
          {pending ? "Preparing…" : "Set up"}
        </button>
      </div>
    );
  }
  return (
    <form action={action} className="space-y-5" noValidate>
      <input type="hidden" name="factorId" value={started.factorId} />
      <input type="hidden" name="next" value={next} />
      <div className="flex flex-col items-center gap-3">
        {/* The QR code is an SVG data URL generated by the authentication service. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={started.qr} alt="QR code to scan with your authenticator app" width={192} height={192} className="rounded border border-grey-200 bg-white p-2" />
        <details className="w-full text-sm">
          <summary className="cursor-pointer font-medium text-teal-dark">Can&apos;t scan? Enter the key by hand</summary>
          <p className="mt-2 break-all rounded bg-grey-100 p-2 font-mono text-xs" data-testid="manual-key">{started.secret}</p>
          <p className="mt-1 text-xs text-grey-500">Keep this key private. Anyone who has it can generate your codes.</p>
        </details>
      </div>
      <div>
        <label htmlFor="code" className="field-label">First code from the app</label>
        <input id="code" name="code" inputMode="numeric" pattern="[0-9]*" autoComplete="one-time-code" maxLength={7} required className="field-input text-center text-2xl tracking-[0.4em]" />
      </div>
      {state.error && <p role="alert" className="rounded-md border border-red-200 bg-red-50 px-3 py-2 text-sm text-red-800">{state.error}</p>}
      <div className="flex gap-3">
        <button type="submit" disabled={confirming} className="btn-primary flex-1 justify-center disabled:opacity-60">{confirming ? "Checking…" : "Turn on"}</button>
        <button type="button" className="btn-outline px-4" onClick={() => start(async () => { await cancelEnrol(); setStarted(null); })}>Cancel</button>
      </div>
    </form>
  );
}
